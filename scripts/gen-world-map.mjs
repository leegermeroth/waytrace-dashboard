// gen-world-map.mjs — one-shot generator for the inline world basemap.
//
// Produces src/lib/worldMap.ts: a single simplified land-outline SVG path in an
// equirectangular (plate carrée) projection, so the ClickMap can plot raw
// lon/lat with x=(lon+180)/360*W, y=(90-lat)/180*H and have dots land in the
// right place. The path is committed as a static string — the map has NO runtime
// dependency and makes NO external request (required by the dashboard CSP, which
// forbids off-origin img/connect sources; audit finding #18).
//
// Regenerate with: node scripts/gen-world-map.mjs
// Deps are transient (npm i --no-save world-atlas topojson-client); nothing is
// added to package.json.

import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const { feature } = require('topojson-client');
const topo = require('world-atlas/land-110m.json');

const W = 1000;
const H = 500;
const land = feature(topo, topo.objects.land);

// Round to 1 decimal (~0.1px) to keep the path compact but smooth.
const px = (lon) => (((lon + 180) / 360) * W).toFixed(1);
const py = (lat) => (((90 - lat) / 180) * H).toFixed(1);

const parts = [];
const addPolygon = (polygon) => {
  // polygon = [outerRing, ...holes]
  for (const ring of polygon) {
    let d = '';
    ring.forEach(([lon, lat], i) => {
      d += (i === 0 ? 'M' : 'L') + px(lon) + ' ' + py(lat);
    });
    parts.push(d + 'Z');
  }
};

// feature() yields a FeatureCollection; each feature's geometry is a Polygon or
// MultiPolygon.
for (const f of land.features) {
  const g = f.geometry;
  if (g.type === 'Polygon') addPolygon(g.coordinates);
  else if (g.type === 'MultiPolygon') g.coordinates.forEach(addPolygon);
}

const path = parts.join('');
const out = `// GENERATED by scripts/gen-world-map.mjs — do not hand-edit.
// Simplified world land outline (world-atlas land-110m), equirectangular
// projection into a ${W}x${H} viewBox. Plot a point with:
//   x = ((lon + 180) / 360) * ${W}
//   y = ((90 - lat) / 180) * ${H}
export const WORLD_MAP_VIEWBOX = '0 0 ${W} ${H}';
export const WORLD_MAP_WIDTH = ${W};
export const WORLD_MAP_HEIGHT = ${H};
export const WORLD_MAP_PATH =
  '${path}';
`;

const dest = new URL('../src/lib/worldMap.ts', import.meta.url);
writeFileSync(dest, out);
console.log(`worldMap.ts written: ${parts.length} rings, path ${(path.length / 1024).toFixed(1)} KB`);
